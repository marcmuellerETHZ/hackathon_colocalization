#!/usr/bin/env python
"""Regenerate the live-state section of RESEARCH_TREE.md (between LIVE markers) from the orch registries.
Usage: python scripts/pi_livestate.py <path/to/RESEARCH_TREE.md> [orch_home]"""
import datetime as dt
import os
import re
import sys
from pathlib import Path

import yaml

tree = Path(sys.argv[1])
home = Path(sys.argv[2] if len(sys.argv) > 2 else os.environ.get("ORCH_HOME", "."))
jobs = yaml.safe_load((home / "JOBS.yaml").read_text())["jobs"]
tasks = yaml.safe_load((home / "TASKS.yaml").read_text())["tasks"]
arts = yaml.safe_load((home / "ARTIFACTS.yaml").read_text())["artifacts"]
now = dt.datetime.now().astimezone()


def el(j):
    t = dt.datetime.fromisoformat(j["start"])
    return f"{(now - t).total_seconds() / 60:.0f}/{j['expected_min']:.0f}m"


owner_jobs = {}
for j in jobs:
    owner_jobs.setdefault(j.get("task") or j.get("owner"), []).append(j)
mark = {"done": "[x]", "running": "[~]", "blocked": "[b]", "planned": "[ ]", "failed": "[-]", "abandoned": "[-]"}
counts = {s: sum(j["status"] == s for j in jobs) for s in ("running", "queued", "done", "failed", "killed", "lost")}
unacked = sum(j["status"] in ("failed", "lost") and not j.get("acked") for j in jobs)
lines = [f"### {now:%Y-%m-%d %H:%M} — Live state (auto-generated by scripts/pi_livestate.py at each heartbeat)",
         f"Jobs: {counts['running']} running, {counts['queued']} queued, {counts['done']} done, "
         f"{counts['failed']} failed ({unacked} unhandled), {counts['lost']} lost. FROZEN (frozen-v1). PHASE 1 closed 05:06 (REPORT.md). PHASE 2 CLOSED 18:45 (D29): no candidate; all verdicts independently verified; test v2 unused; REPORT.md §11 final. Nothing running.", "",
         "| Task | State | Running jobs (elapsed/expected) | Queued jobs | Recent artifacts |", "|---|---|---|---|---|"]
for t in tasks:
    if t["status"] in ("done",) and not any(j["status"] in ("running", "queued") for j in
                                            owner_jobs.get(t["id"], [])):
        continue
    tj = [j for j in jobs if j.get("task") == t["id"]]
    run = ", ".join(f"{j['id']} ({el(j)})" for j in tj if j["status"] == "running") or "—"
    q = sum(j["status"] == "queued" for j in tj)
    outs = [f"{a['name']}@{a['version']}" for a in arts if a.get("producing_job") in {j["id"] for j in tj}]
    lines.append(f"| {t['id']} | {mark.get(t['status'], t['status'])} | {run} | {q or '—'} | {', '.join(outs[-3:]) or '—'} |")
untasked = [j for j in jobs if j["status"] in ("running", "queued") and not j.get("task")]
if untasked:
    lines.append(f"| (jobs without task id) | | {', '.join(j['id'] for j in untasked if j['status'] == 'running') or '—'} "
                 f"| {sum(j['status'] == 'queued' for j in untasked)} | |")
done_tasks = [t["id"] for t in tasks if t["status"] == "done"]
lines += ["", f"Done tasks: {', '.join(done_tasks)}", ""]
block = "<!-- LIVE START -->\n" + "\n".join(lines) + "\n<!-- LIVE END -->"
s = tree.read_text()
if "<!-- LIVE START -->" in s:
    s = re.sub(r"<!-- LIVE START -->.*?<!-- LIVE END -->", lambda m: block, s, flags=re.S)
else:
    s = s.replace("## Status summary (latest first)\n", "## Status summary (latest first)\n\n" + block + "\n\n", 1)
tree.write_text(s)
print("\n".join(lines[:3]))
