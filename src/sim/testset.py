"""Evaluation-grid generator: the frozen test set (DESIGN v4 §8.6, configs/testset_v1.yaml) and its validation
mirror (valid_grid_v1). Entry point named in the test-set config: `sim.testset:generate`.

TEST LOCK (DESIGN §7.3). Test-split loci are produced ONLY inside an authorised test run:
  * `generate(config, out_dir, seed)` with split "test" (the default) refuses unless
      - eval.io.has_test_access() is True (a `started` nonce of scripts/eval_test.py at a frozen-* tagged HEAD), and
      - the call stack contains scripts/eval_test.py;
  * every writer below goes through eval.io.write_locus_set, whose guard refuses test-split loci without access;
  * sim.windows.split_windows("test") refuses without access.
Validation dry runs: `generate(config, out_dir, split="valid", dry_run=True, ...)` (or the CLI below). Test loci
are never generated by this module's CLI.

Main grid (34 cells): mismatch levels x pairing/overlap from the config; L3 and L6 only with zero overlap.
Per cell: n_S S, n_W W, n_D D stratified uniformly over the 5 r² x 4 d strata as feasible (GridPlan, staged
relaxation, README D17), G and U kept as they arise up to the cap each. P1 cells nested; P3 cells eQTL x eQTL /
lab x lab 50:50; test rho positive, validation both signs (DESIGN v4 §2.4).
Shifted arm (DESIGN v4 §8.5/§8.6): pool-swap world (target = mosaic of pool-B haplotypes), levels L1swap /
L2swap half each, P1 nested r_p in {0, 0.6} half each, locus-type mixture S .15 / D .15 / W .5 / M .2,
biobank-strong 50%, background 50%, up to 4 causal per trait; random draws with seed derive(20261028,
"shifted", ...); fill "natural" (every candidate kept: the shifted class mix is part of the shift; README D18).

CLI (validation only):
  python -m sim.testset --config configs/testset_v1.yaml --set valid_grid_v1 --split valid --seed 20261029 \
      --n-per-class 300 --n-gu 100 --workers 4
"""
from __future__ import annotations

