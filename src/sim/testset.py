ROOT = Path(__file__).resolve().parents[2]
POP_LEVELS = ("L3", "L6")          # combined only with zero overlap (DESIGN v4 §2.2, §8.6)
# staged relaxation of the D strata (README D17): stage 1 after K1_PER_D * n_D candidates, stage 2 after K2_PER_D * n_D
K1_PER_D = 100
K2_PER_D = 200


class NaturalPlan:
    """Keep every candidate (no rejection on the oracle class) until n loci; buckets = oracle class."""

    def __init__(self, n: int):
        self.n = int(n)
        self.targets = {"all": self.n}

    def bucket_of(self, orc):
        return orc.cls

    def assign(self, orc, k, filled):
        return orc.cls if sum(filled.values()) < self.n else None

    def done(self, filled):
        return sum(filled.values()) >= self.n

    def describe(self):
        return {"type": "natural", "n": self.n}


@dataclass
class GridSpec:
    cells: list
    n_S: int
    n_D: int
    n_W: int
    n_GU: int


def main_grid_cells(config: dict, split: str) -> list[CellSpec]:
    mg = config["main_grid"]
    both = split != "test"           # DESIGN v4 §2.4: training/validation both signs of rho, test positive
    out = []
    for lvl in mg["mismatch_levels"]:
        for e in mg["pairing_overlap"]:
            pairing, val = e["pairing"], float(e["value"])
            if lvl in POP_LEVELS and val != 0.0:
                continue
            if pairing == "P1":
                nest = e.get("nesting", "nested")
                out.append(CellSpec(cell_id(lvl, "P1", val), lvl, "P1", val, p1_mode=nest))
            elif pairing == "P2":
                out.append(CellSpec(cell_id(lvl, "P2", val), lvl, "P2", val))
            elif pairing == "P3":
                out.append(CellSpec(cell_id(lvl, "P3", val), lvl, "P3", val, both_signs=both))
            else:
                raise ValueError(pairing)
    n_exp = mg.get("n_cells")
    if n_exp is not None and int(n_exp) != len(out):
        raise ValueError(f"config n_cells = {n_exp} but the grid with the L3/L6 exclusions has {len(out)} cells")
    if mg.get("cells") is not None and [c.cell_id for c in out] != list(mg["cells"]):
        raise ValueError("config main_grid.cells differs from the grid derived from levels x pairing_overlap")
    return out


def d_strata_by(config: dict) -> str:
    """'r2' (uniform over r² bins; configs/testset_v1.yaml D_generation_strata) or 'r2xd'."""
    st = config.get("per_cell", {}).get("D_generation_strata", {})
    return {"r2": "r2", "r2xd": "r2xd", "r2_x_d": "r2xd"}.get(str(st.get("by", "r2")), "r2")


def shifted_cells(config: dict) -> list[tuple[CellSpec, int]]:
    sa = config["shifted_arm"]
    n = int(sa["n_loci"])
    mix = sa.get("class_mix", dict(params.SHIFTED_LTYPES))
    ltypes = tuple((k, float(v)) for k, v in mix.items())
    arch = (("p_strong", float(sa.get("biobank_strong_share", 0.5))),
            ("bg_share", float(sa.get("polygenic_background_share", 0.5))),
            ("m_max", int(sa.get("max_causal_per_trait", 4))))
    if sa.get("cells"):
        subs = []
        for e in sa["cells"]:
            lvl, pr, ov = e["cell_id"].split("|")
            assert pr == "P1", e
            subs.append((lvl, float(ov.split("=")[1]), int(e["n"])))
        if sum(x[2] for x in subs) != n:
            raise ValueError("shifted_arm.cells counts do not add up to n_loci")
    else:
        levels = list(sa.get("levels", ["L1swap", "L2swap"]))
        rps = sa.get("pairing", {}).get("r_p", [0.0, 0.6])
        pairs = [(lvl, float(rp)) for lvl in levels for rp in rps]
        per, rem = divmod(n, len(pairs))
        subs = [(l, r, per + (1 if i < rem else 0)) for i, (l, r) in enumerate(pairs)]
    out = []
    for lvl, rp, k in subs:
        if lvl not in ("L1swap", "L2swap"):
            raise ValueError(f"shifted arm level {lvl!r} is not a pool-swap level")
        cs = CellSpec(cell_id(lvl, "P1", rp), lvl, "P1", rp, p1_mode="nested", ltype_weights=ltypes, arch=arch)
        out.append((cs, k))
    return out


def _called_from_eval_test() -> bool:
    for fr in inspect.stack():
        f = Path(fr.filename).resolve()
        if f.name == "eval_test.py" and f.parent.name == "scripts":
            return True
    return False


def _check_access(split: str, dry_run: bool, in_worker: bool = False):
    """in_worker: called inside a pool worker of generate(), whose parent already passed the full check. A spawned
    worker's call stack never contains scripts/eval_test.py, so there only has_test_access() (the nonce of the
    open eval_test.py run, inherited through the environment) is required (review p2.review_sim, defect 1)."""
    if split == "test":
        from eval.io import TestSplitAccessError, has_test_access
        if dry_run:
            raise TestSplitAccessError("a dry run never uses the test split")
        if not (has_test_access() and (in_worker or _called_from_eval_test())):
            raise TestSplitAccessError("test loci are produced only inside scripts/eval_test.py (DESIGN §7.3)")
    elif split in ("valid", "validation"):
        if not dry_run:
            raise ValueError("non-test splits are dry runs: pass dry_run=True")
    else:
        raise ValueError(f"split {split!r}: only 'test' (eval_test.py) or 'valid' (dry run)")


def _worker(args):
    (set_name, cells, plan, split, seed, out_dir, K, M, prefix, log_path, chroms, max_visits) = args
    import torch
    torch.cuda.set_device(0)
    _check_access(split, split != "test", in_worker=True)
    lf = open(log_path, "a") if log_path else None

    def log(s):
        if lf:
            lf.write(s + "\n")
            lf.flush()
    st = build_set(set_name, cells, None, None, split, seed, Path(out_dir), K=K, M=M, plan=plan, log=log,
                   key_prefix=prefix, chroms=chroms, max_visits=max_visits)
    if lf:
        lf.close()
    return st


def _run_groups(set_name, groups, split, seed, out_dir, K, M, prefix, workers, log_dir, chroms, max_visits):
    jobs = []
    for i, (cells, plan) in enumerate(groups):
        tag = re.sub(r"[^A-Za-z0-9._=-]+", "_", cells[0].cell_id) if len(cells) == 1 else f"w{i}"
        lp = str(Path(log_dir) / f"{set_name}.{tag}.log") if log_dir else None
        jobs.append((set_name, cells, plan, split, seed, str(out_dir), K, M, prefix, lp, chroms, max_visits))
    if workers <= 1:
        return [_worker(j) for j in jobs]
    import multiprocessing as mp
    ctx = mp.get_context("spawn")
    with ctx.Pool(min(workers, len(jobs))) as pool:
        return pool.map(_worker, jobs, chunksize=1)


def generate(config: dict, out_dir, seed: int | None = None, *, split: str = "test", dry_run: bool = False,
             set_name: str | None = None, n_per_class: int | None = None, n_gu: int | None = None,
             shifted: bool = True, main: bool = True, workers: int = 4, K: int = 200, M: int = 3,
             k1_per_d: int = K1_PER_D, k2_per_d: int = K2_PER_D, n_shifted: int | None = None,
             cells_filter=None, chroms=None, max_visits=None, log_dir=None, log=print,
             stats_suffix: str = "") -> list[Path]:
    """Generate the main grid (+ shifted arm). Returns the locus-set HDF5 paths (truth parquet alongside)."""
    split = "valid" if split == "validation" else split
    _check_access(split, dry_run)
    seed = int(config.get("seed", TEST_SEED) if seed is None else seed)
    assert seed in SEEDS, seed
    pc = config.get("per_cell", {})
    nS = int(n_per_class or pc.get("S", 400))
    nD = int(n_per_class or pc.get("D", 400))
    nW = int(n_per_class or pc.get("W", 400))
    gu = pc.get("G_U", {"max": 200})
    nGU = int(n_gu if n_gu is not None else (gu.get("max", 200) if isinstance(gu, dict) else gu))
    base = set_name or (f"testset_v{config.get('version', 1)}" if split == "test" else "valid_grid_dry")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    log_dir = Path(log_dir) if log_dir else out_dir
    paths = []
    t0 = time.time()
    meta = {"config_version": config.get("version"), "split": split, "seed": seed, "dry_run": dry_run,
            "world_version": params.WORLD_VERSION}
    if main:
        cells = main_grid_cells(config, split)
        if cells_filter:
            # keep the caller's order (eval.testrun passes the slowest cells first so the longest cell is not left
            # to the end of the pool; each cell's draws are keyed by its own rng, so the order changes no locus)
            pos = {cid: i for i, cid in enumerate(cells_filter)}
            cells = sorted([c for c in cells if c.cell_id in pos], key=lambda c: pos[c.cell_id])
        plan = GridPlan(nS, nD, nW, nGU, nGU, k1_per_d * nD, k2_per_d * nD, by=d_strata_by(config))
        # one group per cell ordered by expected cost; workers pick cells as they free up
        groups = [([c], plan) for c in cells]
        stats = _run_groups(base, groups, split, seed, out_dir, K, M, (), workers, log_dir, chroms, max_visits)
        m, t = link_set(base, out_dir)
        merged = _merge_stats(stats, meta, time.time() - t0)
        (out_dir / f"{base}.stats{stats_suffix}.json").write_text(json.dumps(merged, indent=1))
        paths.append(m)
        log(f"main grid: {len(cells)} cells -> {m} ({time.time()-t0:.0f}s)")
    if shifted and "shifted_arm" in config:
        t1 = time.time()
        sname = base + "_shifted"
        groups = []
        for cs, n in shifted_cells(config):
            if n_shifted is not None:
                n = max(1, int(round(n * n_shifted / int(config["shifted_arm"]["n_loci"]))))
            groups.append(([cs], NaturalPlan(n)))
        stats = _run_groups(sname, groups, split, seed, out_dir, 10, 10, ("shifted",), workers, log_dir, chroms,
                            max_visits)
        m, t = link_set(sname, out_dir)
        merged = _merge_stats(stats, dict(meta, seed_derivation="rng(20261028, 'shifted', set, cell, ...)"),
                              time.time() - t1)
        (out_dir / f"{sname}.stats.json").write_text(json.dumps(merged, indent=1))
        paths.append(m)
        log(f"shifted arm -> {m} ({time.time()-t1:.0f}s)")
    return paths


def _merge_stats(stats: list, meta: dict, runtime: float) -> dict:
    out = dict(meta)
    out["runtime_wall_s"] = runtime
    out["cells"] = {}
    out["workers"] = []
    for s in stats:
        out["cells"].update(s["cells"])
        out["workers"].append({k: v for k, v in s.items() if k != "cells"})
    return out


def main():
    import yaml
    ap = argparse.ArgumentParser(description="Validation dry run of the evaluation grid (never the test split)")
    ap.add_argument("--config", default=str(ROOT / "configs/testset_v1.yaml"))
    ap.add_argument("--set", required=True)
    ap.add_argument("--seed", type=int, default=20261029)
    ap.add_argument("--n-per-class", type=int, default=None)
    ap.add_argument("--n-gu", type=int, default=None)
    ap.add_argument("--n-shifted", type=int, default=None)
    ap.add_argument("--no-shifted", action="store_true")
    ap.add_argument("--no-main", action="store_true")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--cells", nargs="*", default=None)
    ap.add_argument("--chroms", nargs="*", default=None)
    ap.add_argument("--max-visits", type=int, default=None)
    ap.add_argument("--K", type=int, default=200, help="candidates per cell per window visit")
    ap.add_argument("--stats-suffix", default="")
    ap.add_argument("--M", type=int, default=3, help="max accepted per bucket per window visit")
    ap.add_argument("--out", default=str(ROOT / "data/processed/sets"))
    a = ap.parse_args()
    cfg = yaml.safe_load(Path(a.config).read_text())
    paths = generate(cfg, a.out, a.seed, split="valid", dry_run=True, set_name=a.set, n_per_class=a.n_per_class,
                     n_gu=a.n_gu, shifted=not a.no_shifted, main=not a.no_main, workers=a.workers,
                     n_shifted=a.n_shifted, cells_filter=a.cells, chroms=a.chroms, max_visits=a.max_visits, K=a.K, M=a.M,
                     stats_suffix=a.stats_suffix,
                     log_dir=ROOT / "logs/sim", log=lambda s: print(s, flush=True))
    print(json.dumps([str(p) for p in paths]))


if __name__ == "__main__":
    main()
